    private static void Assert(bool ok) { if (!ok) throw new Exception("Reference preview assertion failed."); }
    private static async Task Throws<T>(Func<Task> action) where T : Exception
    {
        try { await action(); } catch (T) { return; } throw new Exception("Expected reference preview refusal.");
    }
    private static JsonObject Reply(string nonce) => JsonNode.Parse(JsonSerializer.Serialize(new {
        schemaVersion = 2, previewOnly = true, contentContinuityVerified = false, accessGranted = false, fileBytesFetched = false,
        identityContinuityMatched = true, matches = new { samePrincipal = true, sameGateway = true, sameRoot = true,
            sameRootGeneration = true, sameRootFingerprint = true, sameStaff = true, sameAccessSubject = true,
            sameAdmissionVersion = true, sameCanonicalPath = true, oldLogicalIdMatchesCurrentContext = true,
            newGrantCurrent = true, newGrantMatchesReference = true, rootMetadataMatches = true, newGrantRechecked = true },
        bindings = new { oldReferenceSHA256 = Sha(Old), newReferenceSHA256 = Sha(New),
            requestNonceSHA256 = Sha(nonce), sessionBindingSHA256 = new string('f', 64) }
    }))!.AsObject();
    private static HttpResponseMessage Json(string value) => new(HttpStatusCode.OK) { Content = new StringContent(value, Encoding.UTF8, "application/json") };
    // Test-only capture of the real client's serialized request, without its synthetic Access token.
    // Inputs must be generated by the isolated server fixture; no request reaches a network.
    internal static async Task CaptureFixtureAsync(string oldReference, string newReference, string oldLogicalId)
    {
        using var fixture = new Fixture();
        var handler = new Handler(async (request, _) => {
            var body = JsonNode.Parse(await request.Content!.ReadAsStringAsync());
            Console.WriteLine(JsonSerializer.Serialize(new { method = request.Method.Method, url = request.RequestUri!.AbsoluteUri,
                origin = request.Headers.GetValues("Origin").Single(), contentType = request.Content.Headers.ContentType!.MediaType,
                accept = request.Headers.Accept.Single().MediaType, fetchSite = request.Headers.TryGetValues("Sec-Fetch-Site", out var values) ? values.Single() : null,
                body }));
            return new HttpResponseMessage(HttpStatusCode.Conflict);
        });
        using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, handler);
        await Throws<ResourceUnavailableException>(() => client.CompareSelectorsAsync(oldReference, newReference, oldLogicalId));
        Assert(handler.Calls == 1);
    }
    private static async Task<string> Nonce(HttpRequestMessage request)
    {
        Assert(request.Method == HttpMethod.Post && request.RequestUri == new Uri("https://ops.example.invalid/api/staff/files/reference-transition/v1/preview"));
        Assert(request.Headers.GetValues("Origin").Single() == "https://ops.example.invalid");
        Assert(request.Headers.Accept.Single().MediaType == "application/json" && request.Headers.AcceptEncoding.Single().Value == "identity");
        Assert(request.Content?.Headers.ContentType?.MediaType == "application/json" && request.Headers.Contains("Cf-Access-Token"));
        using var doc = JsonDocument.Parse(await request.Content!.ReadAsStringAsync()); var root = doc.RootElement;
        Assert(root.EnumerateObject().Count() == 5 && root.GetProperty("schemaVersion").GetInt32() == 2 &&
            root.GetProperty("oldResourceRef").GetString() == Old && root.GetProperty("newResourceRef").GetString() == New &&
            root.GetProperty("oldLogicalFileId").GetString() == Logical);
        return root.GetProperty("requestNonce").GetString()!;
    }
    private static async Task RoundTrip()
    {
        using var fixture = new Fixture(); var nonces = new List<string>();
        var handler = new Handler(async (request, _) => { var nonce = await Nonce(request); nonces.Add(nonce); return Json(Reply(nonce).ToJsonString()); });
        using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, handler);
        var first = await client.CompareSelectorsAsync(Old, New, Logical); var second = await client.CompareSelectorsAsync(Old, New, Logical);
        Assert(handler.Calls == 2 && fixture.Runner.Calls == 2 && nonces.Count == 2 && nonces[0] != nonces[1]);
        Assert(first.OldReferenceSha256 == Sha(Old) && first.NewReferenceSha256 == Sha(New) && first.RequestNonceSha256 == Sha(nonces[0]) &&
            second.RequestNonceSha256 == Sha(nonces[1]) && first.SessionBindingSha256 == new string('f', 64));
        Assert(!first.ToString().Contains(Old, StringComparison.Ordinal) && !first.ToString().Contains(New, StringComparison.Ordinal));
    }
    private static async Task Inputs()
    {
        using var fixture = new Fixture(); var handler = new Handler((_, _) => throw new Exception("Unsafe request reached HTTP."));
        using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, handler);
        foreach (var bad in new[] { "", "odqr1_", "https://elsewhere.invalid/ref", "odqr1_a/b", "odqr1_a\n", "odqr1_" + new string('a', 16379), "ODQR1_x" }) {
            await Throws<TransferException>(() => client.CompareSelectorsAsync(bad, New, Logical));
            await Throws<TransferException>(() => client.CompareSelectorsAsync(Old, bad, Logical));
        }
        foreach (var bad in new[] { "", "oef1_", "oef1_" + new string('A', 64), Logical + "x" })
            await Throws<TransferException>(() => client.CompareSelectorsAsync(Old, New, bad));
        foreach (var bad in new[] { "short", new string('a', 129), "nonce_with_bad/slash" }) {
            using var invalidNonce = new EmployeeReferenceTransitionPreviewClient(fixture.Session,
                new Handler((_, _) => throw new Exception("Unsafe nonce reached HTTP.")), () => bad);
            await Throws<TransferException>(() => invalidNonce.CompareSelectorsAsync(Old, New, Logical));
        }
        Assert(handler.Calls == 0 && fixture.Runner.Calls == 0);
    }
    private static async Task Bindings()
    {
        using var fixture = new Fixture(); var changes = new List<Action<JsonObject>>();
        foreach (var field in Reply("fixture_nonce_123456")["matches"]!.AsObject().Select(x => x.Key)) {
            var selected = field; changes.Add(root => root["matches"]![selected] = false);
        }
        foreach (var field in new[] { "previewOnly", "identityContinuityMatched" }) { var selected = field; changes.Add(root => root[selected] = false); }
        foreach (var field in new[] { "contentContinuityVerified", "accessGranted", "fileBytesFetched" }) { var selected = field; changes.Add(root => root[selected] = true); }
        foreach (var field in new[] { "oldReferenceSHA256", "newReferenceSHA256", "requestNonceSHA256" }) { var selected = field; changes.Add(root => root["bindings"]![selected] = new string('0', 64)); }
        changes.Add(root => root["bindings"]!["sessionBindingSHA256"] = new string('F', 64));
        changes.Add(root => root["schemaVersion"] = 1); changes.Add(root => root["previewOnly"] = "true");
        changes.Add(root => root["matches"]!["samePrincipal"] = null);
        changes.Add(root => root["bindings"]!.AsObject().Remove("requestNonceSHA256"));
        changes.Add(root => root["matches"]!.AsObject().Remove("sameCanonicalPath"));
        foreach (var change in changes) {
            var handler = new Handler(async (request, _) => { var body = Reply(await Nonce(request)); change(body); return Json(body.ToJsonString()); });
            using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, handler);
            await Throws<TransferException>(() => client.CompareSelectorsAsync(Old, New, Logical)); Assert(handler.Calls == 1);
        }
        // A response replayed for a previous request cannot pass the new random challenge.
        var replay = Reply("previous_request_nonce_123");
        using var replayClient = new EmployeeReferenceTransitionPreviewClient(fixture.Session, new Handler((_, _) => Task.FromResult(Json(replay.ToJsonString()))));
        await Throws<TransferException>(() => replayClient.CompareSelectorsAsync(Old, New, Logical));
    }
    private static async Task Framing()
    {
        using var fixture = new Fixture();
        foreach (var mutate in new Func<string, string>[] {
            text => text.Replace("\"schemaVersion\":2", "\"schemaVersion\":2,\"schemaVersion\":2", StringComparison.Ordinal),
            text => text.Replace("\"samePrincipal\":true", "\"samePrincipal\":true,\"samePrincipal\":true", StringComparison.Ordinal),
            text => text.Replace("\"previewOnly\":true", "\"unknown\":0,\"previewOnly\":true", StringComparison.Ordinal),
            text => text.Replace("\"samePrincipal\":true", "\"unknown\":0,\"samePrincipal\":true", StringComparison.Ordinal),
            text => text.Replace("\"sessionBindingSHA256\":", "\"unknown\":0,\"sessionBindingSHA256\":", StringComparison.Ordinal),
            text => text.Replace("\"schemaVersion\":2", "\"schemaVersion\":2.0", StringComparison.Ordinal),
            _ => "{", _ => "[]", _ => new string(' ', 8193)
        }) {
            using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, new Handler(async (request, _) => Json(mutate(Reply(await Nonce(request)).ToJsonString()))));
            await Throws<TransferException>(() => client.CompareSelectorsAsync(Old, New, Logical));
        }
        foreach (var kind in new[] { "type", "charset", "encoding", "utf8", "unbounded" }) {
            using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, new Handler(async (request, _) => {
                var reply = Json(Reply(await Nonce(request)).ToJsonString());
                if (kind == "type") reply.Content.Headers.ContentType!.MediaType = "text/html";
                if (kind == "charset") reply.Content.Headers.ContentType!.CharSet = "utf-16";
                if (kind == "encoding") reply.Content.Headers.ContentEncoding.Add("gzip");
                if (kind == "utf8") { reply.Content = new ByteArrayContent([0xff]); reply.Content.Headers.ContentType = new("application/json"); }
                if (kind == "unbounded") { reply.Content = new StreamContent(new Unseekable(new byte[8193])); reply.Content.Headers.ContentType = new("application/json"); }
                return reply;
            }));
            await Throws<TransferException>(() => client.CompareSelectorsAsync(Old, New, Logical));
        }
    }
    private static async Task Failures()
    {
        using var fixture = new Fixture();
        foreach (var status in new[] { 401, 403, 404, 409, 302, 429, 503, 700 }) {
            var handler = new Handler((_, _) => Task.FromResult(new HttpResponseMessage((HttpStatusCode)status)));
            using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, handler);
            if (status == 401) await Throws<LoginRequiredException>(() => client.CompareSelectorsAsync(Old, New, Logical));
            else if (status == 403) await Throws<AccessDeniedException>(() => client.CompareSelectorsAsync(Old, New, Logical));
            else if (status is 404 or 409) await Throws<ResourceUnavailableException>(() => client.CompareSelectorsAsync(Old, New, Logical));
            else await Throws<TransferException>(() => client.CompareSelectorsAsync(Old, New, Logical));
            Assert(handler.Calls == 1);
        }
        foreach (var error in new Exception[] { new HttpRequestException("private-detail"), new IOException("private-detail"), new OperationCanceledException("private-detail") }) {
            using var client = new EmployeeReferenceTransitionPreviewClient(fixture.Session, new Handler((_, _) => throw error));
            try { await client.CompareSelectorsAsync(Old, New, Logical); throw new Exception("Expected transport failure."); }
            catch (TransferException failure) { Assert(failure.InnerException is null && !failure.Message.Contains("private-detail", StringComparison.Ordinal)); }
        }
        using var cancel = new CancellationTokenSource(); cancel.Cancel(); var runnerCalls = fixture.Runner.Calls;
        var unused = new Handler((_, _) => throw new Exception("Cancelled request reached HTTP."));
        using var cancelled = new EmployeeReferenceTransitionPreviewClient(fixture.Session, unused);
        await Throws<OperationCanceledException>(() => cancelled.CompareSelectorsAsync(Old, New, Logical, cancel.Token));
        Assert(unused.Calls == 0 && fixture.Runner.Calls == runnerCalls);
        using var during = new CancellationTokenSource();
        using var pending = new EmployeeReferenceTransitionPreviewClient(fixture.Session, new Handler(async (_, token) => {
            during.Cancel(); await Task.Delay(Timeout.Infinite, token); throw new Exception("Unreachable");
        }));
        await Throws<OperationCanceledException>(() => pending.CompareSelectorsAsync(Old, New, Logical, during.Token));
        // A response stream may signal EOF while cancellation wins that final read.
        // It must not publish selector evidence after the request was cancelled.
        using var atEof = new CancellationTokenSource();
        using var eofClient = new EmployeeReferenceTransitionPreviewClient(fixture.Session, new Handler(async (request, _) => {
            var bytes = Encoding.UTF8.GetBytes(Reply(await Nonce(request)).ToJsonString());
            var reply = new HttpResponseMessage(HttpStatusCode.OK) { Content = new StreamContent(new CancelAtEof(bytes, atEof)) };
            reply.Content.Headers.ContentType = new("application/json"); return reply;
        }));
        await Throws<OperationCanceledException>(() => eofClient.CompareSelectorsAsync(Old, New, Logical, atEof.Token));
    }
    private sealed class Handler(Func<HttpRequestMessage, CancellationToken, Task<HttpResponseMessage>> action) : HttpMessageHandler
    {
        internal int Calls;
        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken token) { Calls++; return action(request, token); }
    }
    private sealed class Unseekable(byte[] bytes) : MemoryStream(bytes) { public override bool CanSeek => false; }
    private sealed class CancelAtEof(byte[] bytes, CancellationTokenSource cancel) : MemoryStream(bytes)
    {
        public override ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken token = default)
        {
            if (Position == Length) { cancel.Cancel(); return ValueTask.FromResult(0); }
            return base.ReadAsync(buffer, token);
        }
    }
    private sealed class Runner : IAccessCommandRunner
    {
        internal int Calls;
        public Task<AccessCommandResult> RunAsync(string path, IReadOnlyList<string> args, CancellationToken token)
        {
            token.ThrowIfCancellationRequested(); Calls++;
            Assert(args.SequenceEqual(new[] { "access", "token", "--app", "https://ops.example.invalid/api/staff/files/roots" }));
            var payload = Convert.ToBase64String(JsonSerializer.SerializeToUtf8Bytes(new { sub = "synthetic-owner", exp = DateTimeOffset.UtcNow.ToUnixTimeSeconds() + 3600 }))
                .TrimEnd('=').Replace('+', '-').Replace('/', '_');
            return Task.FromResult(new AccessCommandResult(0, "eyJhbGciOiJSUzI1NiJ9." + payload + ".c2ln", ""));
        }
    }
    private sealed class Fixture : IDisposable
    {
        private readonly string root = System.IO.Path.Combine(AppContext.BaseDirectory, "reference-preview-fixture-" + Guid.NewGuid().ToString("N"));
        internal Runner Runner { get; } = new();
        internal CloudflareAccessSession Session { get; }
        internal Fixture()
        {
            Directory.CreateDirectory(root); var binary = System.IO.Path.Combine(root, "synthetic-never-executed.bin");
            File.WriteAllText(binary, "generated helper pin only");
            Session = new(new Uri("https://ops.example.invalid/api/staff/files/roots"), binary,
                Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(binary))), Runner);
        }
        public void Dispose()
        {
            var full = System.IO.Path.GetFullPath(root); var parent = System.IO.Path.GetFullPath(AppContext.BaseDirectory);
            if (!full.StartsWith(parent, StringComparison.OrdinalIgnoreCase) || !System.IO.Path.GetFileName(full).StartsWith("reference-preview-fixture-", StringComparison.Ordinal))
                throw new IOException("Synthetic fixture scope changed.");
            Directory.Delete(full, true);
        }
    }
