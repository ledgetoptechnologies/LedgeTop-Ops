    private const string Old = "odqr1_old_fixture", New = "odqr1_new_fixture";
    private static string Logical => "oef1_" + new string('a', 64);
    private static string Sha(string value) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)));
    internal static IEnumerable<(string Name, Func<Task> Run)> Groups => [
        ("reference preview binds exact POST and fresh nonce without granting file access", RoundTrip),
        ("reference preview rejects unsafe inputs before credential or HTTP use", Inputs),
