using System.Security.Cryptography;
using System.Text;
using System.Xml.Linq;
using LedgeTop.WindowsDownload;

internal static class ExplorerDemoSourceTests
{
    internal static IEnumerable<(string Name, Func<Task> Run)> Groups => [
        ("Explorer generated manifest has valid pins and actual readable documents", ValidDocuments),
        ("Explorer source refuses unsigned session, unknown references and modified metadata", Metadata),
        ("Explorer generated transfer preserves existing destinations and resumes cancellation", Resume),
        ("Explorer revocation fences an old stream even after a fresh simulated sign-in", Revocation)
    ];

    private static void Check(bool value) { if (!value) throw new Exception("Explorer generated source contract failed."); }
    private static async Task Refuse(Func<Task> action)
    {
        try { await action(); }
        catch (Exception error) when (error is TransferException or LoginRequiredException or ResourceUnavailableException or IOException) { return; }
        throw new Exception("Expected generated source refusal.");
    }

    private static async Task ValidDocuments()
    {
        using var source = new ExplorerDemoSource(signedIn: true, chunkDelay: TimeSpan.Zero);
        using var other = new ExplorerDemoSource(signedIn: true, chunkDelay: TimeSpan.Zero);
        Check(source.Entries.Count == 5 && source.Entries.SequenceEqual(other.Entries));
        Check((await source.GetSessionAsync()).PrincipalId == source.PrincipalId);
        foreach (var entry in source.Entries) {
            Check(PlaceholderIdentity.Decode(entry.Identity.Encode()) == entry.Identity);
            Check(!entry.RelativePath.Contains("..", StringComparison.Ordinal) && !Path.IsPathRooted(entry.RelativePath));
            var resolved = await source.ResolveAsync(entry.Identity.ResourceReference);
            Check(resolved.PrincipalId == entry.Identity.PrincipalId && resolved.Spec.Length == entry.Identity.Length);
            using var destination = new Fixture();
            var path = await source.DownloadAsync(resolved.Spec, destination.Path);
            var bytes = await File.ReadAllBytesAsync(path);
            Check(bytes.LongLength == entry.Identity.Length && Convert.ToHexStringLower(SHA256.HashData(bytes)) == entry.Identity.Sha256);
            if (path.EndsWith(".svg", StringComparison.Ordinal)) Check(XDocument.Parse(Encoding.UTF8.GetString(bytes)).Root?.Name.LocalName == "svg");
            if (path.EndsWith(".csv", StringComparison.Ordinal)) {
                var rows = Encoding.UTF8.GetString(bytes).Split("\r\n", StringSplitOptions.RemoveEmptyEntries);
                Check(rows.Length == 24001 && rows.All(row => row.Split(',').Length == 4));
            }
            if (entry.RelativePath.EndsWith("empty.txt", StringComparison.Ordinal)) Check(bytes.Length == 0);
        }
    }

    private static async Task Metadata()
    {
        using var source = new ExplorerDemoSource(chunkDelay: TimeSpan.Zero);
        var entry = source.Entries[0];
        await Refuse(() => source.GetSessionAsync());
        await Refuse(() => source.ResolveAsync(entry.Identity.ResourceReference));
        source.SignIn();
        await Refuse(() => source.ResolveAsync("odqr1_../../outside"));
        var spec = (await source.ResolveAsync(entry.Identity.ResourceReference)).Spec;
        using var destination = new Fixture();
        foreach (var changed in new[] {
            spec with { FileName = "../outside.txt" }, spec with { Sha256 = new string('0', 64) },
            spec with { ContentUri = new Uri("https://elsewhere.invalid/content") }, spec with { Length = spec.Length + 1 },
            spec with { ETag = "\"changed\"" }, spec with { OpaqueIdentity = "different" }
        }) await Refuse(() => source.DownloadAsync(changed, destination.Path));
        Check(!Directory.EnumerateFileSystemEntries(destination.Path).Any());
    }

    private static async Task Resume()
    {
        using var source = new ExplorerDemoSource(signedIn: true, chunkDelay: TimeSpan.FromMilliseconds(8));
        var entry = source.Entries.Single(item => item.RelativePath.EndsWith(".csv", StringComparison.Ordinal));
        var spec = (await source.ResolveAsync(entry.Identity.ResourceReference)).Spec;
        using var destination = new Fixture();
        using var cancellation = new CancellationTokenSource();
        try {
            await source.DownloadAsync(spec, destination.Path, new Observer(progress => {
                if (progress.Phase == DownloadPhase.Receiving && progress.BytesTransferred > 0) cancellation.Cancel();
            }), cancellation.Token);
            throw new Exception("Cancellation did not interrupt generated bytes.");
        } catch (OperationCanceledException) when (cancellation.IsCancellationRequested) { }
        var final = Path.Combine(destination.Path, spec.FileName);
        Check(!File.Exists(final));
        long firstOffset = -1;
        var path = await source.DownloadAsync(spec, destination.Path, new Observer(progress => {
            if (firstOffset == -1 && progress.Phase == DownloadPhase.Receiving) firstOffset = progress.BytesTransferred;
        }));
        Check(firstOffset > 0 && Convert.ToHexStringLower(SHA256.HashData(await File.ReadAllBytesAsync(path))) == spec.Sha256);
        var original = await File.ReadAllBytesAsync(path);
        await Refuse(() => source.DownloadAsync(spec, destination.Path));
        var preserved = await File.ReadAllBytesAsync(path);
        Check(original.SequenceEqual(preserved));
    }

    private static async Task Revocation()
    {
        using var source = new ExplorerDemoSource(signedIn: true, chunkDelay: TimeSpan.FromMilliseconds(8));
        var entry = source.Entries.Single(item => item.RelativePath.EndsWith(".csv", StringComparison.Ordinal));
        var spec = (await source.ResolveAsync(entry.Identity.ResourceReference)).Spec;
        using var destination = new Fixture();
        var changed = false;
        await Refuse(() => source.DownloadAsync(spec, destination.Path, new Observer(progress => {
            if (!changed && progress.Phase == DownloadPhase.Receiving && progress.BytesTransferred > 0) {
                changed = true; source.Revoke(); source.SignIn();
            }
        })));
        Check(changed && !File.Exists(Path.Combine(destination.Path, spec.FileName)));
        await source.DownloadAsync(spec, destination.Path);
        source.Revoke();
        await Refuse(() => source.ResolveAsync(entry.Identity.ResourceReference));
        Check(File.Exists(Path.Combine(destination.Path, spec.FileName)));
    }

    private sealed class Observer(Action<DownloadProgress> update) : IProgress<DownloadProgress> { public void Report(DownloadProgress value) => update(value); }
    private sealed class Fixture : IDisposable
    {
        public string Path { get; } = System.IO.Path.Combine(System.IO.Path.GetTempPath(), "ltfiles-explorer-source-" + Guid.NewGuid().ToString("N"));
        public Fixture() => Directory.CreateDirectory(Path);
        public void Dispose()
        {
            // Only this fixture's own randomly named temp directory can be removed; refuse reparse substitutions.
            if (!Directory.Exists(Path)) return;
            Walk(Path);
            Directory.Delete(Path);
        }
        private void Walk(string current)
        {
            var full = System.IO.Path.GetFullPath(current);
            if (full != Path && !full.StartsWith(Path + System.IO.Path.DirectorySeparatorChar, StringComparison.Ordinal)) throw new Exception("Fixture escaped its root.");
            foreach (var entry in Directory.EnumerateFileSystemEntries(full)) {
                var attributes = File.GetAttributes(entry);
                if ((attributes & FileAttributes.ReparsePoint) != 0) throw new Exception("Refusing changed fixture reparse path.");
                if ((attributes & FileAttributes.Directory) != 0) { Walk(entry); Directory.Delete(entry); }
                else File.Delete(entry);
            }
        }
    }
}
